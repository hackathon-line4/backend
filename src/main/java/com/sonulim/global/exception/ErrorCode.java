package com.sonulim.global.exception;

/**
 * Notion "에러 코드" 목록의 전체 33개 코드. HTTP 상태는 그 목록에 적힌 [NNN] 값이다.
 */
public enum ErrorCode {

	// Base — 공통 규칙 문서의 REST 공통 오류
	VALIDATION_FAILED(400),
	IDEMPOTENCY_KEY_REQUIRED(400),
	IDEMPOTENCY_KEY_REUSED(422),
	UNAUTHORIZED(401),
	TOKEN_EXPIRED(401),
	ROLE_REQUIRED(403),
	ROLE_MISMATCH(403),
	NOT_FOUND(404),
	FIELD_READ_ONLY(400),
	INTERNAL_ERROR(500),

	// Auth
	INVALID_CREDENTIALS(401),
	TOO_MANY_ATTEMPTS(429),
	INVALID_REFRESH_TOKEN(401),
	EMAIL_ALREADY_EXISTS(409),
	AGREEMENT_REQUIRED(400),
	ROLE_ALREADY_SET(409),
	RESET_TOKEN_INVALID(400),

	// Link
	LINK_CODE_NOT_FOUND(404),
	LINK_CODE_EXPIRED(410),
	ALREADY_LINKED(409),
	LINK_REQUEST_NOT_PENDING(409),
	LINK_ENDED(409),

	// Message
	MESSAGE_NOT_WAITING(409),
	MESSAGE_NOT_RESPONDABLE(409),
	SIGNAL_DELETED(409),

	// Signal
	RHYTHM_INVALID(400),
	RHYTHM_DUPLICATE(409),
	PRESET_IN_USE(409),
	TEMPLATE_ALREADY_ADDED(409),
	SIGNAL_NOT_EDITABLE(400),
	FAVORITE_LIMIT_EXCEEDED(400),

	// Location
	LOCATION_SHARING_OFF(409),
	LOCATION_ALREADY_SET(409);

	private final int httpStatus;

	ErrorCode(int httpStatus) {
		this.httpStatus = httpStatus;
	}

	public int getHttpStatus() {
		return httpStatus;
	}
}
